//! Add configurable timeline stress projects to the existing dev setup.
use anyhow::{bail, Context};
use fira_api::{
    plan_stress_seed::{self, Config},
    seed,
};
use sqlx::postgres::PgPoolOptions;
use std::time::Instant;
use uuid::Uuid;

#[tokio::main]
async fn main() -> anyhow::Result<()> {
    dotenvy::dotenv().ok();
    let mut config = Config::default();
    let mut workspace = seed::id(seed::TEAM_WORKSPACE_SLUG);
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        if arg == "--help" || arg == "-h" {
            println!("plan_history_seed [--revisions 1000,10000,50000] [--tasks 200] [--days 90] [--workspace UUID]\nUses DATABASE_URL, like the existing API/seed commands. Defaults to the normal Default workspace.\nAdds stress projects; reruns replace only projects generated by this seeder.");
            return Ok(());
        }
        let value = args.next().context("Expected a value after the option")?;
        match arg.as_str() {
            "--revisions" => {
                config.revisions = value.split(',').map(str::parse).collect::<Result<_, _>>()?
            }
            "--tasks" => config.tasks = value.parse()?,
            "--days" => config.days = value.parse()?,
            "--workspace" => workspace = value.parse::<Uuid>()?,
            _ => bail!("Unknown option: {arg}"),
        }
    }
    config.validate()?;
    let url = std::env::var("DATABASE_URL")
        .unwrap_or_else(|_| "postgres://fira:fira@localhost:5432/fira".into());
    let pool = PgPoolOptions::new()
        .max_connections(5)
        .connect(&url)
        .await?;
    let started = Instant::now();
    plan_stress_seed::seed_profiles(&pool, workspace, &config).await?;
    let title: String = sqlx::query_scalar("SELECT title FROM workspaces WHERE id=$1")
        .bind(workspace)
        .fetch_one(&pool)
        .await?;
    println!("Done in {:.1}s. Reload your existing app, select {title}, and open a History project in Plan → Past.", started.elapsed().as_secs_f64());
    Ok(())
}
